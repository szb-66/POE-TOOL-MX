const paragraph = (text) => ({ type: 'paragraph', text })
const heading = (text) => ({ type: 'heading', text })
const list = (...items) => ({ type: 'list', items })
const callout = (text, tone = 'info') => ({ type: 'callout', text, tone })

const topic = (moduleId, id, title, summary, keywords, blocks) => Object.freeze({
  id: `module-${moduleId}-${id}`,
  category: 'features',
  title,
  summary,
  keywords,
  blocks: Object.freeze(blocks)
})

const workflow = ({ moduleId, title = '第一次使用', summary, keywords, preparation, steps, success, stop, problems, safety, terms }) => topic(
  moduleId,
  'first-use',
  title,
  summary,
  keywords,
  [
    heading('首次使用前准备'),
    list(...preparation),
    heading('操作步骤'),
    list(...steps),
    heading('如何判断成功'),
    paragraph(success),
    heading('停止与恢复'),
    paragraph(stop),
    heading('常见问题'),
    list(...problems),
    heading('安全边界'),
    callout(safety, 'warning'),
    heading('术语'),
    list(...terms)
  ]
)

const details = (moduleId, id, title, summary, keywords, blocks) => topic(moduleId, id, title, summary, keywords, blocks)

